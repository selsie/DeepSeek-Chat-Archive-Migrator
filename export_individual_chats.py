def sanitize_name(name: str) -> str:
    """Sanitizes chat titles for URL- and filesystem-safe names."""
    cleaned = re.sub(r'[\\/*?:"<>|]', "_", name).strip()
    return re.sub(r'\s+', "_", cleaned)[:65].strip("_")


def get_ordered_messages(msg_list: list) -> list:
    """Traverses the parent_id message tree to restore chronological order."""
    by_id = {m["id"]: m for m in msg_list if isinstance(m, dict) and "id" in m}
    children_map = {mid: [] for mid in by_id}
    roots = []

    for mid, m in by_id.items():
        pid = m.get("parent_id")
        if pid in by_id:
            children_map[pid].append(mid)
        else:
            roots.append(mid)

    roots.sort()
    for cid_list in children_map.values():
        cid_list.sort()

    ordered = []
    visited = set()

    def dfs(node_id):
        if node_id in visited:
            return
        visited.add(node_id)
        ordered.append(by_id[node_id])
        for child_id in children_map[node_id]:
            dfs(child_id)

    for r in roots:
        dfs(r)
    return ordered


def process_single_chat(raw: dict, fallback_id: str, folder_chat_name: str) -> dict:
    """Updates image/file links in an individual chat JSON to the hosted URLs."""
    data = json.loads(json.dumps(raw))
    msg_list = data.get("messages")
    if not isinstance(msg_list, list):
        return data

    ordered_msgs = get_ordered_messages(msg_list)
    file_counter = 1
    url_map_by_msg_id = {}

    for m in ordered_msgs:
        mid = m.get("id")
        if not isinstance(m.get("fragments"), list):
            continue

        attachment_urls = []
        has_image = False

        for frag in m["fragments"]:
            if not isinstance(frag, dict):
                continue
            if (frag.get("type") or "").upper() == "FILE" and isinstance(frag.get("files"), list):
                for fobj in frag["files"]:
                    if not isinstance(fobj, dict):
                        continue
                    rel_path = fobj.get("export_path")
                    orig_name = fobj.get("file_name") or "file.png"
                    ext = Path(orig_name).suffix.lower() or ".png"

                    if rel_path:
                        local_file = BASE_DIR / Path(rel_path)
                        if local_file.exists():
                            new_file_name = f"DeepSeek_{folder_chat_name}_{file_counter:03d}{ext}"
                            file_counter += 1

                            url_folder = quote(folder_chat_name)
                            url_file = quote(new_file_name)
                            full_url = f"{BASE_URL}/{url_folder}/{url_file}"

                            fobj["archived_url"] = full_url
                            fobj["archived_file_name"] = new_file_name

                            attachment_urls.append(full_url)
                            if fobj.get("is_image"):
                                has_image = True

        if attachment_urls and mid is not None:
            url_map_by_msg_id[mid] = (attachment_urls, has_image)

