"""
DeepSeek Individual Chat Splitter & Link Rewriter (export_individual_chats.py)
==============================================================================
Splits and renames raw UUID-named DeepSeek session files (`chat_sessions/*.json`)
into clean, human-readable individual JSON files (`DeepSeek_<Chat_Title>.json`)
without merging them into a single archive.

What this script does:
1. Preserves each conversation as a standalone JSON file with its full original
   message structure intact.
2. Renames cryptic UUID filenames into sanitized, readable titles
   (`DeepSeek_<Chat_Title>.json`), automatically appending a short ID suffix on
   title collisions so no files are overwritten.
3. Rewrites local attachment/image paths inside each JSON to match the exact
   hosted URLs (`BASE_URL/<Chat_Folder>/DeepSeek_<Chat_Title>_001.<ext>`)
   generated by `build_gemini_import.py`.

Output created in the script directory:
- `single_chats_named/` -> Individual renamed `.json` files ready for local
                           archiving, search, or custom RAG/skill workflows.

Usage:
1. Place this script in the root folder of your unzipped DeepSeek export
   (next to `chat_sessions/`).
2. Set `BASE_URL` in the CONFIGURATION section below to match your hosting URL.
3. Run the script (`python export_individual_chats.py` or double-click on Windows).
"""

